//! Compiles the shell's text (`locale/shell/`, ADR 0045) into the binary: one `.wtx` table per
//! language and `shell_keys.rs` (a `Key` constant per string) in OUT_DIR, which `src/i18n.rs`
//! includes. A broken translation (placeholders that differ, a text over its budget) or an
//! `en.tsv` older than the copy modules it is extracted from stops the build with the file and
//! line of the problem: the fix is `cargo run -p shared --bin wol-i18n -- extract crates/shell/locale/shell`.
use shared::i18n::{compile, files};
use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").unwrap_or_default());
    let out = PathBuf::from(std::env::var_os("OUT_DIR").unwrap_or_default());
    let dir = manifest.join("locale/shell");
    println!("cargo:rerun-if-changed=locale/shell");
    println!("cargo:rerun-if-changed=build.rs");
    if let Err(e) = build(&dir, &out) {
        println!("cargo:warning=shell text: see the error below");
        eprintln!("{e}");
        std::process::exit(1);
    }
}

fn build(dir: &Path, out: &Path) -> Result<(), String> {
    for (path, _) in files::sources(dir)? {
        println!("cargo:rerun-if-changed={}", path.display());
    }
    if !files::sources(dir)?.is_empty() {
        let want = files::extracted_text(dir, &files::extract_dir(dir)?);
        let have = std::fs::read_to_string(dir.join("en.tsv")).unwrap_or_default();
        if want != have {
            return Err(format!(
                "{}: out of date with the copy modules in sources.tsv: run `cargo run -p shared --bin wol-i18n -- extract crates/shell/locale/shell`",
                dir.join("en.tsv").display()
            ));
        }
    }
    let unit = files::load_unit(dir)?;
    let keys = compile::keys_rs(&unit, "locale/shell/en.tsv")
        .map_err(|p| files::problems_text(&dir.join("en.tsv"), &p))?;
    write(&out.join("shell_keys.rs"), keys.as_bytes())?;
    // The tables the binary embeds, in a list `src/i18n.rs` includes.
    let mut list = String::from("// Generated by build.rs from locale/shell: do not edit.\n");
    list.push_str("pub const TABLES: &[(&str, &[u8])] = &[\n");
    for (lang, bytes, warnings) in files::compile_dir(dir)? {
        if !warnings.is_empty() {
            println!("cargo:warning={}", warnings.replace('\n', " | "));
        }
        let name = format!("shell.{}.wtx", lang.tag());
        write(&out.join(&name), &bytes)?;
        list.push_str(&format!(
            "    (\"{}\", include_bytes!(concat!(env!(\"OUT_DIR\"), \"/{name}\"))),\n",
            lang.tag()
        ));
    }
    list.push_str("];\n");
    write(&out.join("shell_tables.rs"), list.as_bytes())
}

fn write(p: &Path, bytes: &[u8]) -> Result<(), String> {
    std::fs::write(p, bytes).map_err(|e| format!("{}: {e}", p.display()))
}

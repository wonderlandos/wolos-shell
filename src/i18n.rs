//! The shell's text in the person's language (ADR 0045). `locale/shell/en.tsv` is extracted from
//! the copy modules (`copy_settings.rs`, listed in `locale/shell/sources.tsv`); `build.rs`
//! compiles it, with every translation, into tables embedded in the binary; [`t`] reads a string
//! from them in constant time, without parsing or allocating.
//!
//! Concept: the key constants in [`keys`] are generated, one per string, so a misspelt key is a
//! compile error. Why: a surface never holds its own words, it asks for a key. How to use:
//! `i18n::t(keys::SETTINGS_SOUND_LOUDER)` for the language in use, `i18n::tl(key, lang)` for a
//! given one (goldens, the language picker's preview).
//!
//! Text written where it is used (a page title in `ui/setup.rs`, a line in `copy_installer.rs`)
//! is translated by its English: [`tr`]`("Choose a password.")`, [`tr_fill`] for a template with
//! `{name}`s, [`trn`] for a count. `wol-i18n extract` reads those calls from the files of
//! `locale/shell/sources.tsv` into en.tsv (key made from the English), and the build lists every
//! English with its key, so the lookup is a binary search; an English that is not in the unit
//! (a file not listed yet) shows as written.
//!
//! The language is chosen once per process: [`init`] reads the session's locale (`LC_ALL`,
//! `LC_MESSAGES`, `LANG`), Settings > Language & Region and the first-run Setup call
//! [`set_lang`] when the person picks one, and every surface that keeps text on screen registers a
//! [`watch`]er to relabel itself. `xx` (pseudo-locale) is reachable with `WOL_LANG=xx` for layout
//! tests; it is never offered in a menu.
use shared::i18n::{Catalog, Key, Lang};
use std::cell::RefCell;
use std::sync::LazyLock;

/// One `Key` constant per string of `locale/shell/en.tsv` (generated by build.rs).
pub mod keys {
    include!(concat!(env!("OUT_DIR"), "/shell_keys.rs"));
}

mod embedded {
    include!(concat!(env!("OUT_DIR"), "/shell_tables.rs"));
}

mod sources {
    include!(concat!(env!("OUT_DIR"), "/shell_sources.rs"));
}

/// The key whose English is `english`; None: not a text of the unit.
pub fn key_of(english: &str) -> Option<Key> {
    sources::SOURCES
        .binary_search_by(|(s, _)| (*s).cmp(english))
        .ok()
        .map(|i| Key(sources::SOURCES[i].1))
}

/// Marks `english` in a `const` table as a text to translate (`wol-i18n extract` reads it); the
/// surface that shows it calls [`tr`] on it. Returns it unchanged.
pub const fn n_(english: &str) -> &str {
    english
}

/// `english` in the language in use: its translation, else itself.
pub fn tr(english: &str) -> &str {
    tr_in(english, shared::i18n::lang())
}

/// `english` in `lang`: its translation, else itself.
pub fn tr_in(english: &str, lang: Lang) -> &str {
    match key_of(english) {
        Some(k) => match CATALOG.text(k, lang) {
            "" => english,
            t => t,
        },
        None => english,
    }
}

/// [`tr`] of the template `english`, each `{name}` replaced by its value in `args`.
pub fn tr_fill(english: &str, args: &[(&str, &str)]) -> String {
    shared::i18n::fill(tr(english), args)
}

/// The form for the count `n` of a text with a count (`one`: "About {n} minute remaining",
/// `other`: "About {n} minutes remaining"), in the language in use, `{n}` filled in.
pub fn trn(one: &str, other: &str, n: u64) -> String {
    trn_in(one, other, n, shared::i18n::lang())
}

/// [`trn`] in `lang`.
pub fn trn_in(one: &str, other: &str, n: u64, lang: Lang) -> String {
    let form = match key_of(other) {
        Some(k) => match CATALOG.plural(k, Some(n), lang) {
            "" => None,
            t => Some(t),
        },
        None => None,
    };
    let text = form.unwrap_or(if n == 1 { one } else { other });
    shared::i18n::fill(text, &[("n", &n.to_string())])
}

/// The tables built into this binary. A table that does not parse (a broken build) leaves the
/// catalog empty: every string reads "" rather than the shell refusing to start.
static CATALOG: LazyLock<Catalog> =
    LazyLock::new(|| Catalog::embedded(embedded::TABLES).unwrap_or_else(|_| Catalog::empty()));

/// The text of `key` in the language in use, English where that language lacks it.
pub fn t(key: Key) -> &'static str {
    CATALOG.text(key, shared::i18n::lang())
}

/// The text of `key` in the language in use with each `{name}` replaced by its value in `args`.
pub fn fill(key: Key, args: &[(&str, &str)]) -> String {
    shared::i18n::fill(t(key), args)
}

/// The text of `key` in `lang`.
pub fn tl(key: Key, lang: Lang) -> &'static str {
    CATALOG.text(key, lang)
}

/// The plural form of `key` for the count `n` in the language in use.
pub fn plural(key: Key, n: u64) -> &'static str {
    CATALOG.plural(key, Some(n), shared::i18n::lang())
}

/// The key named `name` (`settings.sound_louder`), for text that comes from data (a Lua plugin).
pub fn find(name: &str) -> Option<Key> {
    CATALOG.find(name)
}

/// Number of strings in the shell's catalog.
pub fn count() -> usize {
    CATALOG.len()
}

/// Whether the shell has a translation table for `lang`.
pub fn has(lang: Lang) -> bool {
    CATALOG.has(lang)
}

/// What a surface does when the language changes.
type Watcher = Box<dyn Fn(Lang)>;

thread_local! {
    static WATCHERS: RefCell<Vec<Watcher>> = const { RefCell::new(Vec::new()) };
}

/// Calls `f` with the new language whenever [`set_lang`] changes it. For the GTK main thread, where
/// every surface lives; a surface registers once, when it is built.
pub fn watch(f: impl Fn(Lang) + 'static) {
    WATCHERS.with_borrow_mut(|w| w.push(Box::new(f)));
}

/// Shows text in `lang` from now on and tells every [`watch`]er (when it changed).
pub fn set_lang(lang: Lang) {
    if shared::i18n::lang() == lang {
        return;
    }
    shared::i18n::set_lang(lang);
    // A watcher may register another: run a copy of the list's length, not the live list.
    let n = WATCHERS.with_borrow(Vec::len);
    for i in 0..n {
        WATCHERS.with_borrow(|w| {
            if let Some(f) = w.get(i) {
                f(lang);
            }
        });
    }
}

/// The language of a locale such as `pt_BR.UTF-8`; English for one the shell has no translation of.
pub fn lang_of(locale: &str) -> Lang {
    Lang::from_posix(locale)
        .or_else(|| Lang::from_tag(locale))
        .unwrap_or(Lang::En)
}

/// The language of the session: `WOL_LANG` (a tag, `xx` included, for layout tests), else the
/// first of `LC_ALL`, `LC_MESSAGES`, `LANG` that is set. Call once at start-up.
pub fn init() {
    // glib's environment, as the rest of the session reads it; `init_from` is what tests drive.
    init_from(|v| gtk::glib::getenv(v).map(|s| s.to_string_lossy().into_owned()));
}

/// [`init`] with the environment as `get` answers it.
pub fn init_from(get: impl Fn(&str) -> Option<String>) {
    set_lang(lang_from(get));
}

/// The language [`init_from`] picks, without changing the process's.
pub fn lang_from(get: impl Fn(&str) -> Option<String>) -> Lang {
    let from = |v: &str| get(v).filter(|s| !s.is_empty());
    let locale = from("WOL_LANG")
        .or_else(|| from("LC_ALL"))
        .or_else(|| from("LC_MESSAGES"))
        .or_else(|| from("LANG"))
        .unwrap_or_default();
    lang_of(&locale)
}

#[cfg(test)]
mod tests {
    use super::*;

    // These tests never change the process's language (`set_lang`): other tests of this binary
    // read English text at the same time. `tests/locale_lang.rs` drives `set_lang` alone.

    #[test]
    fn english_answers_every_key_and_the_pseudo_locale_lengthens_it() {
        assert!(count() > 30);
        let k = key_of("Choose a password.").expect("a Setup text is a key");
        assert_eq!(tl(k, Lang::En), "Choose a password.");
        let xx = tl(k, Lang::Xx);
        assert!(xx.starts_with('[') && xx.chars().count() > tl(k, Lang::En).chars().count());
    }

    #[test]
    fn a_text_is_found_by_its_english_and_unknown_text_shows_as_written() {
        assert_eq!(
            tr_in("Choose a password.", Lang::PtBr),
            "Escolha uma senha."
        );
        assert_eq!(tr_in("Choose a password.", Lang::En), "Choose a password.");
        assert_eq!(
            tr_in("No such text, never extracted", Lang::Ja),
            "No such text, never extracted"
        );
        assert_eq!(key_of("No such text, never extracted"), None);
    }

    #[test]
    fn counts_take_their_language_s_form() {
        let (one, other) = ("About {n} minute remaining", "About {n} minutes remaining");
        assert_eq!(trn_in(one, other, 1, Lang::En), "About 1 minute remaining");
        assert_eq!(trn_in(one, other, 5, Lang::En), "About 5 minutes remaining");
        assert_eq!(trn_in(one, other, 2, Lang::Ru), "Осталось около 2 минут");
        assert_eq!(trn_in(one, other, 21, Lang::Ru), "Осталось около 21 минуты");
        assert_eq!(trn_in(one, other, 5, Lang::Ru), "Осталось около 5 минут");
    }

    #[test]
    fn locales_map_to_languages() {
        assert_eq!(lang_of("pt_BR.UTF-8"), Lang::PtBr);
        assert_eq!(lang_of("ru_RU.UTF-8"), Lang::Ru);
        assert_eq!(lang_of("it_IT.UTF-8"), Lang::It);
        assert_eq!(lang_of("xx"), Lang::Xx);
        assert_eq!(lang_of("es_ES.UTF-8"), Lang::En);
        assert_eq!(lang_of(""), Lang::En);
    }

    #[test]
    fn the_session_language_comes_from_the_first_variable_set() {
        let env = |pairs: &'static [(&str, &str)]| {
            move |v: &str| pairs.iter().find(|p| p.0 == v).map(|p| p.1.to_string())
        };
        assert_eq!(lang_from(env(&[("LANG", "de_DE.UTF-8")])), Lang::De);
        assert_eq!(
            lang_from(env(&[("LANG", "de_DE.UTF-8"), ("LC_ALL", "ja_JP.UTF-8")])),
            Lang::Ja
        );
        assert_eq!(
            lang_from(env(&[("LANG", "de_DE.UTF-8"), ("WOL_LANG", "xx")])),
            Lang::Xx
        );
        assert_eq!(lang_from(env(&[("LC_ALL", ""), ("LANG", "")])), Lang::En);
    }

    /// Every official language has a table in the binary (L10N-2: none ships half-done).
    #[test]
    fn every_offered_language_has_a_table() {
        for l in Lang::SHIPPED {
            assert!(has(l), "{l:?}");
        }
        for (locale, _) in wol_core::region::LANGUAGES {
            assert_ne!(Lang::from_posix(locale), None, "{locale}");
        }
    }
}
